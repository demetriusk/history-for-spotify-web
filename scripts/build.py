#!/usr/bin/env python3
"""Build the extension from the userscript and create a store-upload ZIP."""
import json
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

ROOT = Path(__file__).resolve().parents[1]
EXTENSION = ROOT / 'extension'
source = (ROOT / 'spotify-queue-history.user.js').read_text()
body = source.split('// ==/UserScript==', 1)[1].lstrip()
(EXTENSION / 'history.js').write_text('// Generated by scripts/build.py from spotify-queue-history.user.js.\n' + body)
css = source.split('style.textContent = `', 1)[1].split('`;', 1)[0]
assert '${' not in css, 'Shared popup CSS must be static'
(EXTENSION / 'history.css').write_text('/* Generated from the userscript panel styles. */\n' + css)
manifest = json.loads((EXTENSION / 'manifest.json').read_text())
files = ['manifest.json', 'history.js', 'history.css', 'popup.html', 'popup.js', 'popup.css', *[f'icons/icon-{size}.png' for size in (16, 32, 48, 128)]]
output = ROOT / 'dist' / f'{json.loads((ROOT / "package.json").read_text())["name"]}-{manifest["version"]}.zip'
output.parent.mkdir(exist_ok=True)
with ZipFile(output, 'w', ZIP_DEFLATED) as archive:
    for name in sorted(files):
        info = ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
        info.compress_type = ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        archive.writestr(info, (EXTENSION / name).read_bytes())
    info = ZipInfo('LICENSE', date_time=(2026, 1, 1, 0, 0, 0))
    info.compress_type = ZIP_DEFLATED
    info.external_attr = 0o100644 << 16
    archive.writestr(info, (ROOT / 'LICENSE').read_bytes())
print(output.relative_to(ROOT))
