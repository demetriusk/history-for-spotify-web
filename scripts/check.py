#!/usr/bin/env python3
"""Validate the bundle without installing build dependencies."""
import json
from pathlib import Path
import struct
import re
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / 'extension/manifest.json').read_text())
assert manifest['manifest_version'] == 3
assert len(manifest['description']) <= 132
assert manifest['default_locale'] == 'en'
assert manifest['description'] == '__MSG_extensionDescription__'
for locale in ('en', 'pt_BR', 'es'):
    messages = json.loads((ROOT / f'extension/_locales/{locale}/messages.json').read_text())
    assert 0 < len(messages['extensionDescription']['message']) <= 132
assert len(manifest['name']) <= 75
assert manifest.get('permissions') == ['scripting']
assert manifest.get('host_permissions') == ['https://open.spotify.com/*']
assert manifest['action']['default_popup'] == 'popup.html'
assert manifest['action']['default_icon'] == {str(size): f'icons/toolbar-{size}.png' for size in (16, 24, 32)}
assert not manifest.get('web_accessible_resources')
assert manifest['content_scripts'] == [{
    'matches': ['https://open.spotify.com/*'], 'js': ['history.js'],
    'run_at': 'document_idle', 'world': 'MAIN', 'all_frames': False
}]
body = (ROOT / 'spotify-queue-history.user.js').read_text().split('// ==/UserScript==', 1)[1].lstrip()
expected = '// Generated by scripts/build.py from spotify-queue-history.user.js.\n' + body
assert (ROOT / 'extension/history.js').read_text() == expected, 'Run scripts/build.py after editing the userscript'
translations = body.split('  // Shared with the toolbar popup by scripts/build.py.\n', 1)[1].split('  // End shared translations.', 1)[0]
assert (ROOT / 'extension/i18n.js').read_text() == '// Generated from the userscript translation catalog.\n' + translations
catalogs = json.loads(translations.split('const messages = ', 1)[1].split(';\n    const t', 1)[0])
assert catalogs['pt-BR'].keys() == catalogs['es'].keys()
for catalog in catalogs.values():
    for english, translated in catalog.items():
        assert translated and set(re.findall(r'\{\w+\}', english)) == set(re.findall(r'\{\w+\}', translated))
for script in (body, (ROOT / 'extension/popup.js').read_text()):
    for _, message in re.findall(r'''\bt\((['"])(.*?)\1''', script):
        assert message in catalogs['es'], f'Missing translation: {message}'
css = (ROOT / 'spotify-queue-history.user.js').read_text().split('style.textContent = `', 1)[1].split('`;', 1)[0]
assert (ROOT / 'extension/history.css').read_text() == '/* Generated from the userscript panel styles. */\n' + css
for size in (16, 32, 48, 128):
    png = (ROOT / f'extension/icons/icon-{size}.png').read_bytes()
    assert png[:8] == b'\x89PNG\r\n\x1a\n'
    assert struct.unpack('>II', png[16:24]) == (size, size)
for size in (16, 24, 32):
    png = (ROOT / f'extension/icons/toolbar-{size}.png').read_bytes()
    assert png[:8] == b'\x89PNG\r\n\x1a\n'
    assert struct.unpack('>II', png[16:24]) == (size, size)
    assert png[25] == 6, 'Toolbar icons must retain their alpha channel'
archive = ROOT / 'dist' / f'{json.loads((ROOT / "package.json").read_text())["name"]}-{manifest["version"]}.zip'
with ZipFile(archive) as bundle:
    assert bundle.testzip() is None
    assert sorted(bundle.namelist()) == sorted([
        'manifest.json', 'history.js', 'history.css', 'i18n.js', 'popup.html', 'popup.js', 'popup.css', 'LICENSE',
        *[f'icons/icon-{size}.png' for size in (16, 32, 48, 128)],
        *[f'icons/toolbar-{size}.png' for size in (16, 24, 32)],
        *[f'_locales/{locale}/messages.json' for locale in ('en', 'pt_BR', 'es')]
    ])
    for name in bundle.namelist():
        source = ROOT / ('LICENSE' if name == 'LICENSE' else f'extension/{name}')
        assert bundle.read(name) == source.read_bytes()
print('Manifest, icon sizes, source parity, and ZIP contents pass.')
